/**
 * Normalise programme label so "computer science" still hits curriculum_db.
 */
export function normalizeProgrammeKey(programme) {
  if (!programme || typeof programme !== 'string') return ''
  const t = programme.trim()
  if (curriculum_db[t]) return t
  const lower = t.toLowerCase()
  const keys = Object.keys(curriculum_db)
  const hit = keys.find((k) => k.toLowerCase() === lower)
  return hit || t
}

export const getSubjects = (programme, level, semester) => {
  const key = normalizeProgrammeKey(programme)
  const sem = semester === '2nd' ? '2nd' : '1st'
  const lv = String(level || '100').replace(/\D/g, '') || '100'
  if (curriculum_db[key]?.[lv]?.[sem]) {
    return curriculum_db[key][lv][sem]
  }
  const prog = programme?.trim() || 'your programme'
  const letters = prog.replace(/[^a-zA-Z]/g, '')
  const pfx = (letters.slice(0, 3) || 'GEN').toUpperCase()
  const n = parseInt(lv, 10) || 100
  const hundreds = Math.floor(n / 100) * 100 || 100

  // Never use fake "Introduction to X I" for 200L+ — those are 100L-style titles.
  if (n >= 300) {
    return [
      { code: `${pfx} ${hundreds + 1}`, name: `${prog} — Advanced core I (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 3}`, name: `${prog} — Advanced core II (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 5}`, name: `${prog} — Laboratory / systems (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 7}`, name: `${prog} — Theory & applications (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 9}`, name: `${prog} — Departmental elective A`, credits: 3 },
      { code: `${pfx} ${hundreds + 11}`, name: `${prog} — Departmental elective B`, credits: 3 },
      { code: 'GST 311', name: 'GST / General studies (if registered)', credits: 2 },
    ]
  }
  if (n >= 200) {
    return [
      { code: `${pfx} ${hundreds + 1}`, name: `${prog} — Intermediate core I (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 3}`, name: `${prog} — Intermediate core II (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 5}`, name: `${prog} — Laboratory / practical (${n}L)`, credits: 3 },
      { code: `${pfx} ${hundreds + 7}`, name: `${prog} — Methods & tools (${n}L)`, credits: 3 },
      { code: 'GST 211', name: 'GST / Communication (if registered)', credits: 2 },
    ]
  }
  return [
    { code: `${pfx} 101`, name: `Introduction to ${prog}`, credits: 3 },
    { code: `${pfx} 103`, name: `${prog} — Foundations II`, credits: 3 },
    { code: `${pfx} 105`, name: `${prog} — Practical / tutorial`, credits: 3 },
    { code: 'GST 111', name: 'Communication in English', credits: 2 },
    { code: 'GST 113', name: 'Nigerian Peoples and Culture', credits: 2 },
  ]
}
